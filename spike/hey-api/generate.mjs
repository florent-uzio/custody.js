// @ts-check
// Spike: hey-api candidate. Reuses merge.mjs; does not touch the real generator.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import { createClient } from "@hey-api/openapi-ts"

import {
  INTERNAL_SURFACE,
  mergeOpenApiDocsBySurface,
  PUBLIC_SURFACE,
} from "../../scripts/generate-custody-types/merge.mjs"

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, "..", "..")
const openapiDir = join(repoRoot, "openapi")
const modelsDir = join(repoRoot, "src", "models")
const rawDir = join(modelsDir, "hey-api")

function loadDocs() {
  const entries = readdirSync(openapiDir, { withFileTypes: true })

  const stray = entries.filter((e) => e.isFile() && e.name.endsWith(".json")).map((e) => e.name)
  if (stray.length > 0) {
    throw new Error(
      `OpenAPI specs must live in a channel subfolder (e.g. openapi/official/, ` +
        `openapi/devbox/). Found stray spec(s) directly in openapi/: ${stray.join(", ")}`,
    )
  }

  const channels = entries
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort()

  const docs = []
  for (const channel of channels) {
    const channelDir = join(openapiDir, channel)
    const channelEntries = readdirSync(channelDir, { withFileTypes: true })

    const unknownDirs = channelEntries
      .filter((e) => e.isDirectory() && e.name !== INTERNAL_SURFACE)
      .map((e) => e.name)
    if (unknownDirs.length > 0) {
      throw new Error(
        `A channel folder may only contain specs and an "${INTERNAL_SURFACE}/" ` +
          `subfolder. Found in openapi/${channel}/: ${unknownDirs.join(", ")}`,
      )
    }

    const sources = [
      { surface: PUBLIC_SURFACE, dir: channelDir, prefix: `${channel}/` },
      {
        surface: INTERNAL_SURFACE,
        dir: join(channelDir, INTERNAL_SURFACE),
        prefix: `${channel}/${INTERNAL_SURFACE}/`,
        optional: true,
      },
    ]

    for (const { surface, dir, prefix, optional } of sources) {
      if (optional && !channelEntries.some((e) => e.isDirectory() && e.name === INTERNAL_SURFACE)) {
        continue
      }
      const files = readdirSync(dir)
        .filter((f) => f.endsWith(".json"))
        .sort()
      for (const file of files) {
        const doc = JSON.parse(readFileSync(join(dir, file), "utf8"))
        docs.push({
          file: `${prefix}${file}`,
          channel,
          surface,
          version: doc?.info?.["x-app-version"] ?? "(unknown)",
          doc,
        })
      }
    }
  }

  if (docs.length === 0) throw new Error(`No OpenAPI specs found in ${openapiDir}`)
  return docs
}

const TYPES_FILE = {
  [PUBLIC_SURFACE]: "custody-types.ts",
  [INTERNAL_SURFACE]: "custody-internal-types.ts",
}
const METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"]
const JSON_CT = "application/json"

/** hey-api's name for an operation without operationId (observed: `get__v1_domains_by_domainId_...`). */
function fallbackId(method, path) {
  return `${method}_${path.replace(/\{([^}]+)\}/g, "by_$1").replace(/[/\-.]/g, "_")}`
}

const deref = (doc, o) =>
  o?.$ref ? o.$ref.split("/").reduce((a, k) => (k === "#" ? a : a?.[k]), doc) : o

/** Non-JSON media types: hey-api only emits one type per status, so map simple schemas ourselves. */
function simpleTs(schema, report, where) {
  if (schema?.$ref)
    return `H.${schema.$ref
      .split("/")
      .pop()
      .replace(/[^\w$]/g, "_")}`
  if (schema?.type === "string") return "string"
  if (schema?.type === "number" || schema?.type === "integer") return "number"
  if (schema?.type === "boolean") return "boolean"
  report.nonJsonUnknown.push(where)
  return "unknown"
}

const isJson = (content, ct) => ct === JSON_CT || (ct.includes("json") && !content[JSON_CT])

/** Emit the `paths` / `operations` / `components` adapter over hey-api's types. */
function emitAdapter(surface, merged, names, report, manifestOps) {
  const schemas = Object.keys(merged.components?.schemas ?? {})
  const out = []
  out.push(`/**
 * SPIKE (hey-api): adapter over @hey-api/openapi-ts output, generated by
 * spike/hey-api/generate.mjs from the merged ${surface} spec. Do not edit.
 */
import type * as H from "./hey-api/${surface}/types.gen.js"

type At<T, K extends PropertyKey> = K extends keyof T ? T[K] : never
`)
  out.push(`export interface components {\n  schemas: {`)
  for (const k of schemas) {
    const t = k.replace(/[^\w$]/g, "_")
    if (!names.has(t)) {
      report.missingSchemas.push(`${surface}:${k}`)
      out.push(`    ${JSON.stringify(k)}: unknown`)
    } else out.push(`    ${JSON.stringify(k)}: H.${t}`)
  }
  out.push(
    `  }\n  responses: never\n  parameters: never\n  requestBodies: never\n  headers: never\n  pathItems: never\n}\n`,
  )

  const pathsOut = []
  const opsOut = []
  for (const [path, item] of Object.entries(merged.paths)) {
    const pl = [`  ${JSON.stringify(path)}: {`]
    for (const method of METHODS) {
      const op = item[method]
      if (!op) continue
      const id = op.operationId ?? fallbackId(method, path)
      const typeId = id.replace(/[^\w$]/g, "_")
      const D = `${typeId}Data`
      const R = `${typeId}Responses`
      const E = `${typeId}Errors`
      if (!names.has(D)) report.missingOps.push(`${surface}:${method} ${path} -> ${id}`)
      const params = [...(item.parameters ?? []), ...(op.parameters ?? [])].map((p) =>
        deref(merged, p),
      )
      const has = (w) => params.some((p) => p.in === w)
      const reqd = (w) => params.some((p) => p.in === w && p.required)
      if (has("header") || has("cookie")) report.headerParams.push(`${surface}:${id}`)
      const ok = names.has(D)
      const pathT = has("path") && ok ? `path: H.${D}["path"]` : `path?: never`
      const queryT =
        has("query") && ok ? `query${reqd("query") ? "" : "?"}: H.${D}["query"]` : `query?: never`

      let body = `requestBody?: never`
      if (op.requestBody) {
        const rb = deref(merged, op.requestBody)
        const content = rb.content ?? {}
        const parts = Object.keys(content).map((ct) =>
          isJson(content, ct) && ok
            ? `${JSON.stringify(ct)}: Exclude<H.${D}["body"], undefined>`
            : `${JSON.stringify(ct)}: ${simpleTs(content[ct].schema, report, `${surface}:${id} req ${ct}`)}`,
        )
        body = `requestBody${rb.required ? "" : "?"}: { content: { ${parts.join("; ")} } }`
      }

      const src =
        [names.has(R) ? `H.${R}` : null, names.has(E) ? `H.${E}` : null]
          .filter(Boolean)
          .join(" & ") || "{}"
      const resp = []
      const jsonCodes = []
      for (const [code, r0] of Object.entries(op.responses ?? {})) {
        const r = deref(merged, r0)
        const numeric = /^\d+$/.test(code)
        const key = numeric ? code : JSON.stringify(code)
        let c = `content?: never`
        const content = r?.content
        if (content && Object.keys(content).length) {
          c =
            `content: { ` +
            Object.keys(content)
              .map((ct) =>
                isJson(content, ct)
                  ? `${JSON.stringify(ct)}: At<${src}, ${key}>`
                  : `${JSON.stringify(ct)}: ${simpleTs(content[ct].schema, report, `${surface}:${id} res ${code} ${ct}`)}`,
              )
              .join("; ") +
            ` }`
          if (content[JSON_CT]) jsonCodes.push(code)
        }
        resp.push(`      ${key}: { headers: { [name: string]: unknown }; ${c} }`)
      }
      opsOut.push(
        `  ${JSON.stringify(id)}: {\n    parameters: {\n      ${queryT}\n      header?: never\n      ${pathT}\n      cookie?: never\n    }\n    ${body}\n    responses: {\n${resp.join("\n")}\n    }\n  }`,
      )
      pl.push(`    ${method}: operations[${JSON.stringify(id)}]`)
      manifestOps.push({
        id,
        path,
        method,
        hasPath: has("path"),
        hasQuery: has("query"),
        body: !!deref(merged, op.requestBody)?.content?.[JSON_CT],
        responses: jsonCodes,
      })
    }
    pl.push(`  }`)
    pathsOut.push(pl.join("\n"))
  }
  out.push(`export interface paths {\n${pathsOut.join("\n")}\n}\n`)
  out.push(`export interface operations {\n${opsOut.join("\n")}\n}\n`)
  return { text: out.join("\n"), schemas }
}

async function main() {
  const t0 = Date.now()
  const docs = loadDocs()
  const bySurface = mergeOpenApiDocsBySurface(
    docs.map((d) => ({ doc: d.doc, channel: d.channel, surface: d.surface })),
  )
  rmSync(rawDir, { recursive: true, force: true })
  const report = { missingSchemas: [], missingOps: [], headerParams: [], nonJsonUnknown: [] }
  const manifest = {}
  for (const [surface, { merged }] of Object.entries(bySurface)) {
    const path = join(rawDir, surface)
    await createClient({
      input: merged,
      output: { path, case: "preserve", clean: true },
      plugins: [{ name: "@hey-api/typescript", case: "preserve" }],
      logs: { level: "warn", file: false },
    })
    rmSync(join(path, "index.ts"), { force: true })
    const raw = readFileSync(join(path, "types.gen.ts"), "utf8")
    const names = new Set([...raw.matchAll(/^export type (\w+)/gm)].map((m) => m[1]))
    const ops = []
    const { text, schemas } = emitAdapter(surface, merged, names, report, ops)
    writeFileSync(join(modelsDir, TYPES_FILE[surface]), text)
    manifest[surface] = { schemas, ops }
  }
  writeFileSync(join(here, "manifest.json"), JSON.stringify(manifest))
  console.log("missingSchemas", report.missingSchemas.length, report.missingSchemas.slice(0, 10))
  console.log("missingOps", report.missingOps.length, report.missingOps.slice(0, 10))
  console.log("nonJsonUnknown", report.nonJsonUnknown.length, report.nonJsonUnknown.slice(0, 8))
  console.log("opsWithHeaderParams", report.headerParams.length, report.headerParams.slice(0, 5))
  console.log(`generation ms: ${Date.now() - t0}`)
}
main().catch((e) => {
  console.error(e)
  process.exit(1)
})
