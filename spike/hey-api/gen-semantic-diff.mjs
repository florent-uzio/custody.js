// Emits spike/hey-api/semantic-diff.{public,internal}.ts from manifest.json (written by generate.mjs).
// Each item is one `const _n: Eq<Old..., New...> = true` line so every mismatch is its own tsc error.
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const manifest = JSON.parse(readFileSync(join(here, "manifest.json"), "utf8"))

const FILES = {
  public: { old: "./baseline/old-public", neu: "../../src/models/custody-types" },
  internal: { old: "./baseline/old-internal", neu: "../../src/models/custody-internal-types" },
}

const q = JSON.stringify
const key = (c) => (/^\d+$/.test(c) ? c : q(c))

for (const [surface, { schemas, ops }] of Object.entries(manifest)) {
  const lines = [
    `// Generated by gen-semantic-diff.mjs — ${surface} surface. Do not edit.`,
    `import type * as Old from "${FILES[surface].old}"`,
    `import type * as New from "${FILES[surface].neu}"`,
    `type Eq<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false`,
    ``,
  ]
  const items = []
  let n = 0
  const add = (kind, label, a, b) => {
    const name = `_${n++}`
    items.push({ name, kind, label })
    lines.push(`const ${name}: Eq<${a}, ${b}> = true // ${kind} ${label}`)
  }
  for (const s of schemas) {
    add("schema", s, `Old.components["schemas"][${q(s)}]`, `New.components["schemas"][${q(s)}]`)
  }
  for (const { id, path, method, hasPath, hasQuery, body, responses } of ops) {
    const O = (t) => `Old.paths[${q(path)}][${q(method)}]${t}`
    const N = (t) => `New.paths[${q(path)}][${q(method)}]${t}`
    if (hasPath)
      add(
        "path",
        id,
        `NonNullable<${O('["parameters"]["path"]')}>`,
        `NonNullable<${N('["parameters"]["path"]')}>`,
      )
    if (hasQuery)
      add(
        "query",
        id,
        `NonNullable<${O('["parameters"]["query"]')}>`,
        `NonNullable<${N('["parameters"]["query"]')}>`,
      )
    if (body)
      add(
        "body",
        id,
        `NonNullable<${O('["requestBody"]')}>["content"]["application/json"]`,
        `NonNullable<${N('["requestBody"]')}>["content"]["application/json"]`,
      )
    for (const c of responses)
      add(
        "response",
        `${id} ${c}`,
        O(`["responses"][${key(c)}]["content"]["application/json"]`),
        N(`["responses"][${key(c)}]["content"]["application/json"]`),
      )
  }
  writeFileSync(join(here, `semantic-diff.${surface}.ts`), lines.join("\n") + "\n")
  writeFileSync(join(here, `semantic-diff.${surface}.items.json`), JSON.stringify(items))
  console.log(surface, "items", items.length)
}
