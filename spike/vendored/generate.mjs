// @ts-check
// Spike: run the vendored, pruned openapi-typescript against the same merged docs
// as scripts/generate-custody-types/generate.mjs. Writes to spike/vendored/out/
// (does NOT touch src/models), so the result can be diffed against the baseline.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import {
  INTERNAL_SURFACE,
  mergeOpenApiDocsBySurface,
  PUBLIC_SURFACE,
} from "../../scripts/generate-custody-types/merge.mjs"
import openapiTS, { astToString } from "./openapi-typescript/index.mjs"

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, "..", "..")
const openapiDir = join(repoRoot, "openapi")
const outDir = join(here, "out")

const TYPES_FILE = {
  [PUBLIC_SURFACE]: "custody-types.ts",
  [INTERNAL_SURFACE]: "custody-internal-types.ts",
}

/** @param {string} surface */
function typesHeader(surface) {
  return `/**
 * This file was auto-generated by scripts/generate-custody-types from the
 * merged superset of every ${surface} spec in openapi/. Do not make direct changes.
 */

`
}

// Copied from scripts/generate-custody-types/generate.mjs (loadDocs).
function loadDocs() {
  const entries = readdirSync(openapiDir, { withFileTypes: true })
  const channels = entries
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort()
  const docs = []
  for (const channel of channels) {
    const channelDir = join(openapiDir, channel)
    const channelEntries = readdirSync(channelDir, { withFileTypes: true })
    const sources = [
      { surface: PUBLIC_SURFACE, dir: channelDir },
      { surface: INTERNAL_SURFACE, dir: join(channelDir, INTERNAL_SURFACE), optional: true },
    ]
    for (const { surface, dir, optional } of sources) {
      if (optional && !channelEntries.some((e) => e.isDirectory() && e.name === INTERNAL_SURFACE))
        continue
      for (const file of readdirSync(dir)
        .filter((f) => f.endsWith(".json"))
        .sort()) {
        docs.push({ channel, surface, doc: JSON.parse(readFileSync(join(dir, file), "utf8")) })
      }
    }
  }
  return docs
}

mkdirSync(outDir, { recursive: true })
const bySurface = mergeOpenApiDocsBySurface(docs().map((d) => d))
function docs() {
  return loadDocs()
}
const t0 = performance.now()
for (const [surface, { merged }] of Object.entries(bySurface)) {
  const ast = await openapiTS(merged)
  writeFileSync(join(outDir, TYPES_FILE[surface]), typesHeader(surface) + astToString(ast))
}
console.log(`generated in ${Math.round(performance.now() - t0)} ms`)
