// Generates spike/vendored/semantic-diff.ts: one mutual-assignability assertion
// per components.schemas entry and per operation path/query/requestBody/response
// JSON, comparing the baseline (Old) to the vendored generator output (New).
// Usage: node semantic-diff-gen.mjs   (expects out/*.ts formatted, baseline/old-*.ts)
import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import ts from "typescript-printer"

const here = dirname(fileURLToPath(import.meta.url))
const J = "application/json"

function items(file) {
  const program = ts.createProgram([file], { skipLibCheck: true, strict: true })
  const checker = program.getTypeChecker()
  const sf = program.getSourceFile(file)
  const out = []
  const iface = (n) => sf.statements.find((s) => ts.isInterfaceDeclaration(s) && s.name.text === n)
  const members = (type) => checker.getPropertiesOfType(type)
  const typeOf = (sym, node) => checker.getTypeOfSymbolAtLocation(sym, node)
  const comps = iface("components")
  const compsType = checker.getTypeAtLocation(comps)
  const schemasSym = compsType.getProperty("schemas")
  for (const s of members(typeOf(schemasSym, comps)))
    out.push(`components["schemas"][${JSON.stringify(s.name)}]`)
  const ops = iface("operations")
  const opsType = checker.getTypeAtLocation(ops)
  for (const op of members(opsType)) {
    const opT = typeOf(op, ops)
    const base = `operations[${JSON.stringify(op.name)}]`
    const params = opT.getProperty("parameters") && typeOf(opT.getProperty("parameters"), ops)
    const paramsT = params && checker.getNonNullableType(params)
    for (const k of ["path", "query"]) {
      const p = paramsT?.getProperty(k)
      if (p && !(typeOf(p, ops).flags & ts.TypeFlags.Never))
        out.push(`NonNullable<${base}["parameters"]>["${k}"]`)
    }
    const rb = opT.getProperty("requestBody")
    if (rb) {
      const rbT = checker.getNonNullableType(typeOf(rb, ops))
      const c = rbT.getProperty("content")
      if (c && typeOf(c, ops).getProperty(J))
        out.push(`NonNullable<${base}["requestBody"]>["content"]["${J}"]`)
    }
    const resp = typeOf(opT.getProperty("responses"), ops)
    for (const r of members(resp)) {
      const c = typeOf(r, ops).getProperty("content")
      if (c && typeOf(c, ops).getProperty(J))
        out.push(`${base}["responses"][${JSON.stringify(r.name)}]["content"]["${J}"]`)
    }
  }
  return out
}

let body = `// GENERATED by semantic-diff-gen.mjs. Do not edit.
type Eq<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false
`
let total = 0
for (const [label, oldF, newF] of [
  ["public", "baseline/old-public.ts", "out/custody-types.ts"],
  ["internal", "baseline/old-internal.ts", "out/custody-internal-types.ts"],
]) {
  const list = items(join(here, oldF))
  const tag = label === "public" ? "Pub" : "Int"
  body += `import type { components as Old${tag}C, operations as Old${tag}O } from "./${oldF.replace(/\.ts$/, ".js")}"\n`
  body += `import type { components as New${tag}C, operations as New${tag}O } from "./${newF.replace(/\.ts$/, ".js")}"\n`
  list.forEach((expr, i) => {
    const o = expr.replace(/^components/, `Old${tag}C`).replace(/operations/g, `Old${tag}O`)
    const n = expr.replace(/^components/, `New${tag}C`).replace(/operations/g, `New${tag}O`)
    body += `const ${label}_${i}: Eq<${o}, ${n}> = true // ${expr.replace(/\n/g, " ")}\n`
  })
  console.log(`${label}: ${list.length} items`)
  total += list.length
}
writeFileSync(join(here, "semantic-diff.ts"), body)
console.log(`total ${total}`)
