// Generates spike/dtsgenerator/semantic-diff.{public,internal}.ts (+ .manifest.json mapping line -> item).
// Old = spike/dtsgenerator/baseline/*.ts (openapi-typescript 7.13.0), New = src/models/*.ts (this spike).
import { writeFileSync } from "node:fs"

import { mergeOpenApiDocsBySurface } from "../../scripts/generate-custody-types/merge.mjs"
import { loadDocs } from "./load-docs.mjs"

const METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"]
const q = JSON.stringify
const FILES = { public: "custody-types", internal: "custody-internal-types" }

const by = mergeOpenApiDocsBySurface(loadDocs())
for (const [surface, { merged: doc }] of Object.entries(by)) {
  const f = FILES[surface]
  const lines = [
    `// GENERATED by semantic-diff-gen.mjs (${surface}) - one assertion per line; a tsc error on a line == mismatch`,
    `import type * as Old from "./baseline/${f}.js"`,
    `import type * as New from "../../src/models/${f}.js"`,
    `type Eq<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false`,
    `type Json<R> = R extends { content: infer C } ? (C extends { "application/json": infer U } ? U : "no-json") : "no-content"`,
    `type Body<O> = O extends { requestBody: infer R } ? Json<NonNullable<R>> : O extends { requestBody?: infer R } ? Json<NonNullable<R>> : "no-body"`,
    `type BodyOpt<O> = O extends { requestBody: unknown } ? "required" : O extends { requestBody?: unknown } ? "optional" : "none"`,
  ]
  const manifest = {}
  let n = 0
  const add = (kind, id, expr) => {
    n++
    lines.push(`const _${n}: ${expr} = true`)
    // expr is `Eq<OLD, NEW>`; keep both operands so explain.mjs can re-evaluate them
    const inner = expr.slice(3, -1)
    let depth = 0
    let cut = -1
    for (let i = 0; i < inner.length; i++) {
      const c = inner[i]
      if ("<[(".includes(c)) depth++
      else if (">])".includes(c) && !(c === ">" && inner[i - 1] === "=")) depth--
      else if (c === "," && depth === 0) cut = i
    }
    manifest[lines.length] = { kind, id, old: inner.slice(0, cut), new: inner.slice(cut + 2) }
  }
  for (const k of Object.keys(doc.components.schemas)) {
    add("schema", k, `Eq<Old.components["schemas"][${q(k)}], New.components["schemas"][${q(k)}]>`)
  }
  for (const [p, item] of Object.entries(doc.paths)) {
    for (const m of METHODS) {
      const op = item[m]
      if (!op) continue
      const O = `["paths"][${q(p)}][${q(m)}]`
      const label = `${m} ${p}${op.operationId ? ` (${op.operationId})` : ""}`
      for (const where of ["path", "query", "header"]) {
        if (!(op.parameters ?? []).some((x) => x.in === where)) continue
        add(
          `param.${where}`,
          label,
          `Eq<Old.paths[${q(p)}][${q(m)}]["parameters"][${q(where)}], New.paths[${q(p)}][${q(m)}]["parameters"][${q(where)}]>`,
        )
      }
      if (op.requestBody) {
        add(
          "requestBody.json",
          label,
          `Eq<Body<Old${O}>, Body<New${O}>>`
            .replaceAll('Old["paths"]', "Old.paths")
            .replaceAll('New["paths"]', "New.paths"),
        )
        add(
          "requestBody.optionality",
          label,
          `Eq<BodyOpt<Old${O}>, BodyOpt<New${O}>>`
            .replaceAll('Old["paths"]', "Old.paths")
            .replaceAll('New["paths"]', "New.paths"),
        )
      }
      for (const [code, r] of Object.entries(op.responses ?? {})) {
        const mimes = Object.keys(r.content ?? {})
        if (!mimes.includes("application/json")) continue
        const key = code === "default" ? q("default") : q(code)
        add(
          "response.json",
          `${label} -> ${code}`,
          `Eq<Json<Old.paths[${q(p)}][${q(m)}]["responses"][${key}]>, Json<New.paths[${q(p)}][${q(m)}]["responses"][${key}]>>`,
        )
      }
    }
  }
  writeFileSync(new URL(`./semantic-diff.${surface}.ts`, import.meta.url), lines.join("\n") + "\n")
  writeFileSync(
    new URL(`./semantic-diff.${surface}.manifest.json`, import.meta.url),
    JSON.stringify(manifest),
  )
  console.log(surface, n, "items")
}
